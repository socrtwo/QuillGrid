/**
 * Calculation engine: evaluates formulas, tracks dependencies, spills dynamic arrays, and recalculates
 * only what a change affects.
 *
 * Dependencies are recorded dynamically: every reference a formula touches while it is evaluated is
 * remembered as a precedent, so INDIRECT, OFFSET, names and IF branches are all tracked exactly. A
 * change marks its dependents dirty transitively; dirty formulas are then evaluated on demand (reading a
 * dirty precedent evaluates it first), which gives a correct order without a global topological sort.
 */
import { CellError, ERR, type Scalar, type Matrix, type Cell } from '../model/types';
import { cellKey, keyRow, keyCol, MAX_COLS, MAX_ROWS, parseCell, splitSheetRef, parseRange, type Range } from '../model/address';
import type { Sheet, Workbook } from '../model/workbook';
import { parse, FormulaError, type Node, type RefToken } from './parser';
import {
  Fail, fail, isRef, isRefs, isLambda, isMatrix, toMatrix, toScalar, implicitIntersect, broadcast, compare, num, str,
  type Value, type RefV, type MultiRefV, type LambdaV, type Ctx,
} from './values';
import { getFn, isArrayArg, type FnDef } from './functions/registry';

type FKey = string; // `${sheet.id}:${cellKey}`

interface FInfo {
  sheet: Sheet;
  key: number;
  node: Node | null;
  error: CellError | null;
  precedents: Rec[];
  volatile: boolean;
  spill: Range | null;
}

interface Rec { sheet: Sheet; r1: number; c1: number; r2: number; c2: number }

const BLOCK = 64;

export class Engine {
  private compiled = new Map<string, Node | FormulaError>();
  private info = new Map<FKey, FInfo>();
  private cellDeps = new Map<FKey, Set<FKey>>();          // single cell precedent -> dependents
  private rangeDeps = new Map<string, Map<number, { rec: Rec; f: FKey }[]>>(); // sheet id -> column block -> entries
  private dirty = new Set<FKey>();
  private evaluating = new Set<FKey>();
  private depth = 0;
  private deferred: FKey[] = [];
  private recording: Rec[] | null = null;
  private volatileNow = false;
  circular: FKey[] = [];
  /** Anchors showing #SPILL! because their area is blocked. */
  private blocked = new Set<FKey>();
  private spillers = new Set<FKey>();
  /** Cells whose displayed values changed in the last recalc (for repaint and charts). */
  lastChanged = 0;
  now = new Date();
  private boundsCache = new Map<Sheet, { r2: number; c2: number; v: number }>();
  private calcCount = 0;

  constructor(public book: Workbook) {}

  // ------------------------------------------------------------------------------------------
  // Compilation

  compile(formula: string): Node | FormulaError {
    let n = this.compiled.get(formula);
    if (!n) {
      try { n = parse(formula); } catch (e) { n = e instanceof FormulaError ? e : new FormulaError(String(e)); }
      if (this.compiled.size > 50000) this.compiled.clear();
      this.compiled.set(formula, n);
    }
    return n;
  }

  // ------------------------------------------------------------------------------------------
  // Recalculation

  /** Full rebuild: every formula is dirty. */
  rebuild(): void {
    this.info.clear();
    this.cellDeps.clear();
    this.rangeDeps.clear();
    this.dirty.clear();
    this.blocked.clear();
    this.spillers.clear();
    this.boundsCache.clear();
    for (const sh of this.book.sheets) {
      // Remove stale spill values; they are regenerated by their anchors.
      for (const [k, cell] of sh.cells) if (cell.sp != null && !cell.f) { if (cell.s) sh.cells.set(k, { s: cell.s }); else sh.cells.delete(k); }
      for (const [k, cell] of sh.cells) if (cell.f != null) this.track(sh, k);
    }
  }

  private fkey(sheet: Sheet, k: number): FKey { return sheet.id + ':' + k; }

  private track(sheet: Sheet, k: number): FInfo {
    const fk = this.fkey(sheet, k);
    let inf = this.info.get(fk);
    if (!inf) {
      inf = { sheet, key: k, node: null, error: null, precedents: [], volatile: false, spill: null };
      this.info.set(fk, inf);
    }
    this.dirty.add(fk);
    return inf;
  }

  private untrack(fk: FKey): void {
    const inf = this.info.get(fk);
    if (!inf) return;
    this.removeDeps(fk, inf);
    if (inf.spill) this.clearSpill(inf);
    this.info.delete(fk);
    this.spillers.delete(fk);
    this.blocked.delete(fk);
    this.dirty.delete(fk);
  }

  private removeDeps(fk: FKey, inf: FInfo): void {
    for (const p of inf.precedents) {
      if (p.r1 === p.r2 && p.c1 === p.c2) this.cellDeps.get(this.fkey(p.sheet, cellKey(p.r1, p.c1)))?.delete(fk);
      else {
        const m = this.rangeDeps.get(p.sheet.id);
        if (!m) continue;
        for (const b of this.blocksOf(p)) {
          const list = m.get(b);
          if (list) { const i = list.findIndex((e) => e.f === fk && e.rec === p); if (i >= 0) list.splice(i, 1); }
        }
      }
    }
    inf.precedents = [];
  }

  private blocksOf(p: Rec): number[] {
    if (p.c2 - p.c1 >= MAX_COLS - 1) return [-1];
    const out: number[] = [];
    for (let b = Math.floor(p.c1 / BLOCK); b <= Math.floor(p.c2 / BLOCK); b++) out.push(b);
    return out;
  }

  private addDeps(fk: FKey, inf: FInfo, recs: Rec[]): void {
    const seen = new Set<string>();
    for (const p of recs) {
      const sig = `${p.sheet.id}:${p.r1}:${p.c1}:${p.r2}:${p.c2}`;
      if (seen.has(sig)) continue;
      seen.add(sig);
      inf.precedents.push(p);
      if (p.r1 === p.r2 && p.c1 === p.c2) {
        const ck = this.fkey(p.sheet, cellKey(p.r1, p.c1));
        let s = this.cellDeps.get(ck);
        if (!s) { s = new Set(); this.cellDeps.set(ck, s); }
        s.add(fk);
      } else {
        let m = this.rangeDeps.get(p.sheet.id);
        if (!m) { m = new Map(); this.rangeDeps.set(p.sheet.id, m); }
        for (const b of this.blocksOf(p)) {
          let list = m.get(b);
          if (!list) { list = []; m.set(b, list); }
          list.push({ rec: p, f: fk });
        }
      }
    }
  }

  /** Formulas that read the cell (sheet, r, c). */
  private dependentsOf(sheet: Sheet, r: number, c: number, out: Set<FKey>): void {
    const direct = this.cellDeps.get(this.fkey(sheet, cellKey(r, c)));
    if (direct) for (const f of direct) out.add(f);
    const m = this.rangeDeps.get(sheet.id);
    if (!m) return;
    for (const b of [Math.floor(c / BLOCK), -1]) {
      const list = m.get(b);
      if (!list) continue;
      for (const { rec, f } of list) if (r >= rec.r1 && r <= rec.r2 && c >= rec.c1 && c <= rec.c2) out.add(f);
    }
  }

  /**
   * Applies pending workbook changes and recalculates. Returns true when anything was evaluated.
   * In manual mode, only edited formulas are evaluated unless force is set.
   */
  recalc(force = false): boolean {
    const pending = this.book.takePending();
    this.now = new Date();
    this.boundsCache.clear();
    if (pending.structural || force === true && this.book.calc.mode === 'manual') {
      if (pending.structural) this.rebuild();
      else for (const f of this.info.keys()) this.dirty.add(f);
    }
    const queue: { sheet: Sheet; r: number; c: number }[] = [];
    for (const [sheet, keys] of pending.cells) {
      if (!this.book.sheets.includes(sheet)) continue;
      for (const k of keys) {
        const fk = this.fkey(sheet, k);
        const cell = sheet.cells.get(k);
        if (cell?.f != null) {
          const inf = this.info.get(fk);
          if (inf) this.removeDeps(fk, inf);
          this.track(sheet, k);
        } else if (this.info.has(fk)) this.untrack(fk);
        const r = keyRow(k), c = keyCol(k);
        queue.push({ sheet, r, c });
        // Typing into (or clearing) a cell can block or unblock a dynamic array.
        for (const afk of [...this.spillers, ...this.blocked]) {
          const inf = this.info.get(afk);
          if (!inf || inf.sheet !== sheet || afk === fk) continue;
          const sp = inf.spill;
          if ((sp && r >= sp.r1 && r <= sp.r2 && c >= sp.c1 && c <= sp.c2) || this.blocked.has(afk)) this.dirty.add(afk);
        }
      }
    }
    if (this.book.calc.mode === 'manual' && !force) {
      // Only the edited formulas themselves.
      this.evaluateDirty();
      return true;
    }
    for (const [fk, inf] of this.info) if (inf.volatile) { this.dirty.add(fk); this.enqueueSpill(inf, queue); }
    for (const fk of [...this.dirty]) { const inf = this.info.get(fk); if (inf) queue.push({ sheet: inf.sheet, r: keyRow(inf.key), c: keyCol(inf.key) }); }
    this.propagate(queue);
    const any = this.dirty.size > 0;
    this.evaluateDirty();
    return any || queue.length > 0;
  }

  private enqueueSpill(inf: FInfo, queue: { sheet: Sheet; r: number; c: number }[]): void {
    if (!inf.spill) return;
    const s = inf.spill;
    for (let r = s.r1; r <= s.r2; r++) for (let c = s.c1; c <= s.c2; c++) queue.push({ sheet: inf.sheet, r, c });
  }

  private propagate(queue: { sheet: Sheet; r: number; c: number }[]): void {
    const seen = new Set<string>();
    while (queue.length) {
      const { sheet, r, c } = queue.pop()!;
      const sig = sheet.id + ':' + cellKey(r, c);
      if (seen.has(sig)) continue;
      seen.add(sig);
      const deps = new Set<FKey>();
      this.dependentsOf(sheet, r, c, deps);
      for (const f of deps) {
        const inf = this.info.get(f);
        if (!inf) continue;
        if (!this.dirty.has(f)) this.dirty.add(f);
        queue.push({ sheet: inf.sheet, r: keyRow(inf.key), c: keyCol(inf.key) });
        this.enqueueSpill(inf, queue);
      }
    }
  }

  private evaluateDirty(): void {
    this.circular = [];
    let guard = 0;
    while (this.dirty.size && guard++ < 50) {
      const spilled: { sheet: Sheet; r: number; c: number }[] = [];
      for (const fk of [...this.dirty]) {
        if (!this.dirty.has(fk)) continue;
        const inf = this.info.get(fk);
        if (!inf) { this.dirty.delete(fk); continue; }
        const before = inf.spill;
        this.evalSafely(fk);
        if (!sameRange(before, inf.spill)) {
          const area = unionOf(before, inf.spill);
          if (area) for (let r = area.r1; r <= area.r2; r++) for (let c = area.c1; c <= area.c2; c++) spilled.push({ sheet: inf.sheet, r, c });
        }
      }
      if (!spilled.length) break;
      // A spill area changed: formulas reading those cells must be evaluated again.
      this.propagate(spilled);
    }
    if (this.book.calc.iterative && this.circular.length) this.iterate();
  }

  /** Iterative calculation for circular references. */
  private iterate(): void {
    const loop = [...new Set(this.circular)];
    const max = this.book.calc.maxIterations, eps = this.book.calc.maxChange;
    for (let i = 0; i < max; i++) {
      let delta = 0;
      for (const fk of loop) {
        const inf = this.info.get(fk);
        if (!inf) continue;
        const before = inf.sheet.cells.get(inf.key)?.v;
        this.dirty.add(fk);
        this.evalFormula(fk, inf, true);
        const after = inf.sheet.cells.get(inf.key)?.v;
        if (typeof before === 'number' && typeof after === 'number') delta = Math.max(delta, Math.abs(after - before));
        else if (before !== after) delta = Infinity;
      }
      if (delta <= eps) break;
    }
    this.circular = [];
  }

  /** Evaluates a formula from the top level, resolving deep dependency chains without deep recursion. */
  private evalSafely(fk: FKey): void {
    const stack: FKey[] = [fk];
    let guard = 0;
    while (stack.length && guard++ < 1e7) {
      const cur = stack[stack.length - 1];
      const inf = this.info.get(cur);
      if (!inf || !this.dirty.has(cur)) { stack.pop(); continue; }
      try {
        this.depth = 0;
        this.evalFormula(cur, inf);
        stack.pop();
      } catch (e) {
        if (!(e instanceof DeferError)) throw e;
        this.depth = 0;
        const d = this.deferred.splice(0);
        if (!d.length) { stack.pop(); continue; }
        stack.push(...d);
      }
    }
  }

  /** Evaluates one formula cell and stores its result (and spill). */
  private evalFormula(fk: FKey, inf: FInfo, iterating = false): void {
    this.dirty.delete(fk);
    const sheet = inf.sheet;
    const k = inf.key;
    const cell = sheet.cells.get(k);
    if (!cell || cell.f == null) { this.untrack(fk); return; }
    const r = keyRow(k), c = keyCol(k);
    const compiled = this.compile(cell.f);
    this.removeDeps(fk, inf);
    let result: Value;
    const saveRec = this.recording, saveVol = this.volatileNow;
    const recs: Rec[] = [];
    this.recording = recs;
    this.volatileNow = false;
    this.evaluating.add(fk);
    this.depth++;
    try {
      if (compiled instanceof FormulaError) result = ERR.name;
      else {
        inf.node = compiled;
        result = this.evalNode(compiled, this.makeCtx(sheet, r, c));
      }
    } catch (e) {
      if (e instanceof DeferError) {
        this.depth--;
        this.evaluating.delete(fk);
        this.recording = saveRec;
        this.volatileNow = saveVol;
        this.dirty.add(fk);
        throw e;
      }
      if (e instanceof Fail) result = e.err;
      else if (e instanceof CircularError) { result = iterating || this.book.calc.iterative ? (cell.v ?? 0) : 0; this.circular.push(fk); }
      else { console.error(e); result = ERR.value; }
    }
    this.depth--;
    this.evaluating.delete(fk);
    this.recording = saveRec;
    inf.volatile = this.volatileNow;
    this.volatileNow = saveVol;
    this.addDeps(fk, inf, recs);
    this.calcCount++;
    this.store(inf, sheet, r, c, cell, result);
  }

  private store(inf: FInfo, sheet: Sheet, r: number, c: number, cell: Cell, result: Value): void {
    const ctx = this.makeCtx(sheet, r, c);
    let m: Matrix | null = null;
    if (isRef(result)) {
      if (result.r1 === result.r2 && result.c1 === result.c2) result = ctx.cell(result.sheet, result.r1, result.c1);
      else { try { m = toMatrix(result, ctx); } catch (e) { result = e instanceof Fail ? e.err : ERR.value; } }
    } else if (isRefs(result)) result = ERR.value;
    else if (isLambda(result)) result = ERR.calc;
    else if (isMatrix(result)) m = result;
    const legacy = cell.arr;
    if (m && (m.length > 1 || (m[0]?.length ?? 0) > 1 || legacy)) {
      const rows = legacy ? legacy.r2 - legacy.r1 + 1 : m.length, cols = legacy ? legacy.c2 - legacy.c1 + 1 : m[0].length;
      const area: Range = { r1: r, c1: c, r2: r + rows - 1, c2: c + cols - 1 };
      if (area.r2 >= MAX_ROWS || area.c2 >= MAX_COLS) { this.setAnchor(sheet, r, c, cell, ERR.spill, inf, null); return; }
      // Blocked?
      const anchorKey = cellKey(r, c);
      if (!legacy) {
        for (let rr = area.r1; rr <= area.r2; rr++) for (let cc = area.c1; cc <= area.c2; cc++) {
          if (rr === r && cc === c) continue;
          const x = sheet.cells.get(cellKey(rr, cc));
          if (x && (x.f != null || (x.v != null && x.sp !== anchorKey) || (x.sp != null && x.sp !== anchorKey))) {
            this.setAnchor(sheet, r, c, cell, new CellError('#SPILL!', 'blocked'), inf, null);
            return;
          }
          if (sheet.mergeAt(rr, cc)) { this.setAnchor(sheet, r, c, cell, new CellError('#SPILL!', 'merged'), inf, null); return; }
        }
      }
      // Clear old spill cells outside the new area
      if (inf.spill) {
        const old = inf.spill;
        for (let rr = old.r1; rr <= old.r2; rr++) for (let cc = old.c1; cc <= old.c2; cc++) {
          if (rr >= area.r1 && rr <= area.r2 && cc >= area.c1 && cc <= area.c2) continue;
          this.clearSpillCell(sheet, rr, cc, anchorKey);
        }
      }
      for (let rr = 0; rr < rows; rr++) for (let cc = 0; cc < cols; cc++) {
        if (rr === 0 && cc === 0) continue;
        const v = rr < m.length && cc < (m[0]?.length ?? 0) ? norm(m[rr][cc] ?? 0) : ERR.na;
        const k2 = cellKey(r + rr, c + cc);
        const cur = sheet.cells.get(k2);
        sheet.setComputed(r + rr, c + cc, { ...(cur?.s ? { s: cur.s } : {}), v, sp: anchorKey });
      }
      this.setAnchor(sheet, r, c, cell, norm(m[0]?.[0] ?? null), inf, area);
      return;
    }
    const v = m ? norm(m[0]?.[0] ?? null) : norm(result as Scalar);
    this.setAnchor(sheet, r, c, cell, v, inf, null);
  }

  private setAnchor(sheet: Sheet, r: number, c: number, cell: Cell, v: Scalar, inf: FInfo, spill: Range | null): void {
    const fk = this.fkey(sheet, cellKey(r, c));
    if (v instanceof CellError && v.code === '#SPILL!') this.blocked.add(fk); else this.blocked.delete(fk);
    if (spill) this.spillers.add(fk); else this.spillers.delete(fk);
    if (inf.spill && !spill) this.clearSpill(inf);
    inf.spill = spill;
    const cur = sheet.cells.get(cellKey(r, c)) || cell;
    sheet.setComputed(r, c, { ...cur, v: v ?? (cur.f != null ? 0 : null) });
  }

  private clearSpill(inf: FInfo): void {
    const s = inf.spill;
    if (!s) return;
    const anchorKey = inf.key;
    for (let r = s.r1; r <= s.r2; r++) for (let c = s.c1; c <= s.c2; c++) {
      if (cellKey(r, c) === anchorKey) continue;
      this.clearSpillCell(inf.sheet, r, c, anchorKey);
    }
    inf.spill = null;
  }

  private clearSpillCell(sheet: Sheet, r: number, c: number, anchorKey: number): void {
    const x = sheet.cells.get(cellKey(r, c));
    if (x && x.sp === anchorKey && x.f == null) sheet.setComputed(r, c, x.s ? { s: x.s } : undefined);
  }

  /** Spill range of a formula cell, if it spilled. */
  spillRange(sheet: Sheet, r: number, c: number): Range | null {
    return this.info.get(this.fkey(sheet, cellKey(r, c)))?.spill ?? null;
  }

  precedentsOf(sheet: Sheet, r: number, c: number): Rec[] {
    return this.info.get(this.fkey(sheet, cellKey(r, c)))?.precedents ?? [];
  }

  dependentsOfCell(sheet: Sheet, r: number, c: number): { sheet: Sheet; r: number; c: number }[] {
    const s = new Set<FKey>();
    this.dependentsOf(sheet, r, c, s);
    return [...s].map((f) => this.info.get(f)).filter((x): x is FInfo => !!x).map((i) => ({ sheet: i.sheet, r: keyRow(i.key), c: keyCol(i.key) }));
  }

  formulaCount(): number { return this.info.size; }
  get evaluations(): number { return this.calcCount; }

  // ------------------------------------------------------------------------------------------
  // Context

  makeCtx(sheet: Sheet, r: number, c: number, scope: Map<string, Value> | null = null, rel: { dr: number; dc: number } | null = null): Ctx & { rel: typeof rel } {
    const eng = this;
    const ctx: Ctx & { rel: typeof rel } = {
      book: this.book, sheet, r, c, scope, rel,
      cell: (sh, rr, cc) => eng.readCell(sh, rr, cc),
      // Methods (not arrows): a context copied with a LET/LAMBDA scope ({ ...ctx, scope }) must evaluate in that scope.
      evalNode(n, sc) { return eng.evalNode(n, sc === undefined ? this : { ...this, scope: sc }); },
      callLambda(fn, args) { return eng.callLambda(fn, args, this); },
      volatile: () => { eng.volatileNow = true; },
      usedBounds: (sh) => eng.usedBounds(sh),
      resolveRef: (text, a1) => eng.resolveRefText(text, sheet, a1, r, c),
      now: this.now,
      random: () => Math.random(),
    };
    return ctx;
  }

  usedBounds(sh: Sheet): { r2: number; c2: number } {
    const hit = this.boundsCache.get(sh);
    if (hit && hit.v === sh.cells.size) return hit;
    let r2 = 0, c2 = 0;
    for (const k of sh.cells.keys()) { const r = keyRow(k), c = keyCol(k); if (r > r2) r2 = r; if (c > c2) c2 = c; }
    const b = { r2, c2, v: sh.cells.size };
    this.boundsCache.set(sh, b);
    return b;
  }

  /** Current value of a cell, evaluating it (or its spill anchor) first if dirty. */
  readCell(sheet: Sheet, r: number, c: number): Scalar {
    const k = cellKey(r, c);
    const fk = this.fkey(sheet, k);
    let cell = sheet.cells.get(k);
    if (cell?.f != null) {
      if (this.evaluating.has(fk)) throw new CircularError();
      if (this.dirty.has(fk)) {
        if (this.depth > MAX_DEPTH) { this.deferred.push(fk); throw new DeferError(); }
        const inf = this.info.get(fk) || this.track(sheet, k);
        const saveRec = this.recording;
        this.evalFormula(fk, inf);
        this.recording = saveRec;
        cell = sheet.cells.get(k);
      }
    } else if (cell?.sp != null) {
      const ak = this.fkey(sheet, cell.sp);
      if (this.evaluating.has(ak)) throw new CircularError();
      if (this.dirty.has(ak)) {
        if (this.depth > MAX_DEPTH) { this.deferred.push(ak); throw new DeferError(); }
        const inf = this.info.get(ak);
        if (inf) { const saveRec = this.recording; this.evalFormula(ak, inf); this.recording = saveRec; cell = sheet.cells.get(k); }
      }
    }
    return cell?.v ?? null;
  }

  private record(v: RefV): void {
    if (!this.recording) return;
    const sheets = v.sheets || [v.sheet];
    for (const sh of sheets) this.recording.push({ sheet: sh, r1: v.r1, c1: v.c1, r2: v.r2, c2: v.c2 });
  }

  // ------------------------------------------------------------------------------------------
  // Evaluation

  evalNode(n: Node, ctx: Ctx): Value {
    switch (n.t) {
      case 'num': return n.v;
      case 'str': return n.v;
      case 'bool': return n.v;
      case 'err': return new CellError(n.v);
      case 'missing': return null;
      case 'arr': return n.rows.map((row) => row.map((x) => { const v = this.evalNode(x, ctx); return isMatrix(v) || isRef(v) ? toScalar(v, ctx) : (v as Scalar); }));
      case 'ref': return this.refValue(n.ref, ctx);
      case 'name': return this.nameValue(n.name, n.sheet, ctx);
      case 'sref': return this.structuredRef(n.table, n.spec, ctx);
      case 'fn': return this.callFn(n.name, n.args, ctx);
      case 'call': {
        const callee = n.callee.t === 'name' ? this.nameValue(n.callee.name, n.callee.sheet, ctx) : this.evalNode(n.callee, ctx);
        if (!isLambda(callee)) return ERR.value;
        return this.callLambda(callee, n.args.map((a) => this.evalNode(a, ctx)), ctx);
      }
      case 'un': return this.lift1(this.evalNode(n.a, ctx), ctx, (x) => -num(x));
      case 'pct': return this.lift1(this.evalNode(n.a, ctx), ctx, (x) => num(x) / 100);
      case 'isect': {
        const v = this.evalNode(n.a, ctx);
        return isRef(v) ? implicitIntersect(v, ctx) : isMatrix(v) ? (v[0]?.[0] ?? null) : v;
      }
      case 'spill': {
        const v = this.evalNode(n.a, ctx);
        if (!isRef(v)) return ERR.ref;
        this.readCell(v.sheet, v.r1, v.c1);
        const sp = this.spillRange(v.sheet, v.r1, v.c1);
        if (!sp) return ERR.ref;
        const rv: RefV = { k: 'ref', sheet: v.sheet, ...sp };
        this.record(rv);
        return rv;
      }
      case 'union': {
        const areas: RefV[] = [];
        for (const it of n.items) {
          const v = this.evalNode(it, ctx);
          if (isRef(v)) areas.push(v); else if (isRefs(v)) areas.push(...v.areas); else return ERR.value;
        }
        return { k: 'refs', areas } as MultiRefV;
      }
      case 'bin': return this.binary(n.op, n.a, n.b, ctx);
    }
    return ERR.value;
  }

  private refValue(ref: RefToken, ctx: Ctx): Value {
    let sheet = ctx.sheet;
    if (ref.sheet) {
      const sh = this.book.sheetByName(ref.sheet);
      if (!sh) return ERR.ref;
      sheet = sh;
    }
    let { r1, c1, r2, c2 } = ref;
    const rel = (ctx as any).rel as { dr: number; dc: number } | null;
    if (rel) {
      if (ref.kind !== 'cols') { if (!ref.ar1) r1 += rel.dr; if (!ref.ar2) r2 += rel.dr; }
      if (ref.kind !== 'rows') { if (!ref.ac1) c1 += rel.dc; if (!ref.ac2) c2 += rel.dc; }
      if (r1 < 0 || c1 < 0 || r2 >= MAX_ROWS || c2 >= MAX_COLS) return ERR.ref;
    }
    const rv: RefV = { k: 'ref', sheet, r1: Math.min(r1, r2), c1: Math.min(c1, c2), r2: Math.max(r1, r2), c2: Math.max(c1, c2) };
    if (ref.sheet2) {
      const a = this.book.sheets.findIndex((s) => s.name.toLowerCase() === ref.sheet!.toLowerCase());
      const b = this.book.sheets.findIndex((s) => s.name.toLowerCase() === ref.sheet2!.toLowerCase());
      if (a < 0 || b < 0) return ERR.ref;
      rv.sheets = this.book.sheets.slice(Math.min(a, b), Math.max(a, b) + 1);
    }
    this.record(rv);
    return rv;
  }

  /** Looks up a defined name (sheet scope first), a LET/LAMBDA variable, or a table name. */
  nameValue(name: string, sheetName: string | undefined, ctx: Ctx): Value {
    const up = name.toUpperCase();
    if (!sheetName && ctx.scope) {
      for (const [k, v] of ctx.scope) if (k === up) return v;
    }
    const scopeSheet = sheetName ? this.book.sheetByName(sheetName) : ctx.sheet;
    const def = this.book.names.find((d) => d.name.toUpperCase() === up && d.sheet && scopeSheet && d.sheet.toLowerCase() === scopeSheet.name.toLowerCase())
      || this.book.names.find((d) => d.name.toUpperCase() === up && !d.sheet);
    if (def) {
      const f = def.ref.replace(/^=/, '');
      const node = this.compile(f);
      if (node instanceof FormulaError) return ERR.name;
      const homeSheet = def.sheet ? this.book.sheetByName(def.sheet) || ctx.sheet : ctx.sheet;
      return this.evalNode(node, { ...ctx, sheet: homeSheet, scope: null });
    }
    const t = this.findTable(name);
    if (t) return this.structuredRef(name, '[#Data]', ctx);
    if (/^(TRUE|FALSE)$/.test(up)) return up === 'TRUE';
    return new CellError('#NAME?', name);
  }

  findTable(name: string): { sheet: Sheet; table: import('../model/types').TableDef } | null {
    const up = name.toUpperCase();
    for (const sheet of this.book.sheets) for (const table of sheet.tables) if (table.name.toUpperCase() === up) return { sheet, table };
    return null;
  }

  private structuredRef(tableName: string, spec: string, ctx: Ctx): Value {
    let found = tableName ? this.findTable(tableName) : null;
    if (!tableName) {
      for (const table of ctx.sheet.tables) {
        const rg = table.range;
        if (ctx.r >= rg.r1 && ctx.r <= rg.r2 && ctx.c >= rg.c1 && ctx.c <= rg.c2) { found = { sheet: ctx.sheet, table }; break; }
      }
    }
    if (!found) return ERR.ref;
    const { sheet, table } = found;
    const rg = table.range;
    const hdr = table.opts.header ? 1 : 0, tot = table.opts.totals ? 1 : 0;
    const dataR1 = rg.r1 + hdr, dataR2 = rg.r2 - tot;
    // Parse spec: [Col], [[#Headers],[Col]], [@Col], [@[Col 1]], [[Col1]:[Col2]], [#All], []
    const inner = spec.slice(1, -1).trim();
    const items: string[] = [];
    let thisRow = false;
    if (inner.startsWith('@')) { thisRow = true; const rest = inner.slice(1).trim(); if (rest) items.push(rest.replace(/^\[|\]$/g, '')); }
    else if (!inner.startsWith('[')) { if (inner) items.push(inner); }
    else {
      const re = /\[((?:[^\]']|'.)*)\]|:/g;
      let m: RegExpExecArray | null;
      let pendingRange = false;
      while ((m = re.exec(inner))) {
        if (m[0] === ':') { pendingRange = true; continue; }
        const v = m[1].replace(/'(.)/g, '$1');
        if (pendingRange) { items[items.length - 1] += '\u0000' + v; pendingRange = false; }
        else items.push(v);
      }
    }
    let r1 = dataR1, r2 = dataR2;
    let cols: [number, number] | null = null;
    for (const it of items) {
      const low = it.toLowerCase();
      if (low === '#all') { r1 = rg.r1; r2 = rg.r2; }
      else if (low === '#data') { r1 = dataR1; r2 = dataR2; }
      else if (low === '#headers') { if (!hdr) return ERR.ref; r1 = r2 = rg.r1; }
      else if (low === '#totals') { if (!tot) return ERR.ref; r1 = r2 = rg.r2; }
      else if (low === '#this row') thisRow = true;
      else {
        const [a, b] = it.split('\u0000');
        const ia = table.columns.findIndex((c) => c.name.toLowerCase() === a.toLowerCase());
        const ib = b != null ? table.columns.findIndex((c) => c.name.toLowerCase() === b.toLowerCase()) : ia;
        if (ia < 0 || ib < 0) return ERR.ref;
        cols = [Math.min(ia, ib), Math.max(ia, ib)];
      }
    }
    if (items.some((x) => x.toLowerCase() === '#headers') && items.some((x) => x.toLowerCase() === '#data')) { r1 = rg.r1; r2 = dataR2; }
    if (items.some((x) => x.toLowerCase() === '#data') && items.some((x) => x.toLowerCase() === '#totals')) { r1 = dataR1; r2 = rg.r2; }
    if (thisRow) { if (ctx.r < dataR1 || ctx.r > dataR2) return ERR.value; r1 = r2 = ctx.r; }
    const c1 = rg.c1 + (cols ? cols[0] : 0), c2 = cols ? rg.c1 + cols[1] : rg.c2;
    if (r2 < r1) return ERR.ref;
    const rv: RefV = { k: 'ref', sheet, r1, c1, r2, c2 };
    this.record(rv);
    return rv;
  }

  private callFn(name: string, args: Node[], ctx: Ctx): Value {
    const f = getFn(name);
    if (!f) {
      // A defined name holding a LAMBDA can be called like a function.
      const v = this.nameValue(name, undefined, ctx);
      if (isLambda(v)) return this.callLambda(v, args.map((a) => this.evalNode(a, ctx)), ctx);
      return new CellError('#NAME?', name);
    }
    if (args.length < f.min || args.length > f.max) return ERR.value;
    if (f.volatile) this.volatileNow = true;
    if (f.lazy) {
      try { return f.lazy(args, ctx); } catch (e) { if (e instanceof Fail) return e.err; throw e; }
    }
    const vals: Value[] = [];
    let liftIdx: number[] | null = null;
    for (let i = 0; i < args.length; i++) {
      let v = this.evalNode(args[i], ctx);
      if (!isArrayArg(f, i)) {
        if (isRef(v) && v.r1 === v.r2 && v.c1 === v.c2 && !v.sheets) v = ctx.cell(v.sheet, v.r1, v.c1);
        else if (isMatrix(v) && v.length === 1 && v[0].length === 1) v = v[0][0];
        else if (isRef(v) || isMatrix(v)) (liftIdx ||= []).push(i);
        else if (isRefs(v)) return ERR.value;
      }
      vals.push(v);
    }
    if (liftIdx) {
      const mats = liftIdx.map((i) => toMatrix(vals[i], ctx));
      return broadcast(mats, (...xs) => {
        const a = vals.slice();
        liftIdx!.forEach((i, j) => { a[i] = xs[j]; });
        const out = this.invoke(f, a, ctx);
        return isMatrix(out) ? (out[0]?.[0] ?? null) : isRef(out) ? toScalar(out, ctx) : (out as Scalar);
      });
    }
    return this.invoke(f, vals, ctx);
  }

  private invoke(f: FnDef, args: Value[], ctx: Ctx): Value {
    try {
      const r = f.impl!(args, ctx);
      if (typeof r === 'number' && !Number.isFinite(r)) return ERR.num;
      if (r === undefined) return null;
      return r;
    } catch (e) {
      if (e instanceof Fail) return e.err;
      if (e instanceof CircularError) throw e;
      if (e instanceof RangeError) return ERR.num;
      throw e;
    }
  }

  callLambda(fn: LambdaV, args: Value[], ctx: Ctx): Value {
    if (args.length > fn.params.length) return ERR.value;
    const scope = new Map(fn.scope || []);
    fn.params.forEach((p, i) => scope.set(p.toUpperCase(), i < args.length ? args[i] : null));
    return this.evalNode(fn.body, { ...ctx, scope });
  }

  private lift1(v: Value, ctx: Ctx, f: (x: Scalar) => Scalar): Value {
    if (isRef(v) || isMatrix(v)) {
      const m = toMatrix(v, ctx);
      if (m.length === 1 && m[0].length === 1) return wrap(() => f(m[0][0]));
      return broadcast([m], f);
    }
    if (isRefs(v) || isLambda(v)) return ERR.value;
    return wrap(() => f(v as Scalar));
  }

  private binary(op: string, an: Node, bn: Node, ctx: Ctx): Value {
    if (op === ':') return this.rangeOp(this.evalNode(an, ctx), this.evalNode(bn, ctx));
    if (op === ' ') {
      const a = this.evalNode(an, ctx), b = this.evalNode(bn, ctx);
      if (!isRef(a) || !isRef(b) || a.sheet !== b.sheet) return ERR.value;
      const r1 = Math.max(a.r1, b.r1), c1 = Math.max(a.c1, b.c1), r2 = Math.min(a.r2, b.r2), c2 = Math.min(a.c2, b.c2);
      if (r1 > r2 || c1 > c2) return ERR.null;
      return { k: 'ref', sheet: a.sheet, r1, c1, r2, c2 } as RefV;
    }
    const a = this.evalNode(an, ctx), b = this.evalNode(bn, ctx);
    const fn = BINOPS[op];
    if (!fn) return ERR.value;
    const scalarOf = (v: Value): Scalar | null | undefined => {
      if (isRef(v)) return v.r1 === v.r2 && v.c1 === v.c2 && !v.sheets ? ctx.cell(v.sheet, v.r1, v.c1) : undefined;
      if (isMatrix(v)) return v.length === 1 && v[0].length === 1 ? v[0][0] : undefined;
      if (isRefs(v) || isLambda(v)) return ERR.value;
      return v as Scalar;
    };
    const sa = scalarOf(a), sb = scalarOf(b);
    if (sa !== undefined && sb !== undefined) return wrap(() => fn(sa, sb));
    return broadcast([toMatrix(a, ctx), toMatrix(b, ctx)], (x, y) => fn(x, y));
  }

  private rangeOp(a: Value, b: Value): Value {
    if (!isRef(a) || !isRef(b)) return ERR.value;
    if (a.sheet !== b.sheet) return ERR.value;
    const rv: RefV = { k: 'ref', sheet: a.sheet, r1: Math.min(a.r1, b.r1), c1: Math.min(a.c1, b.c1), r2: Math.max(a.r2, b.r2), c2: Math.max(a.c2, b.c2) };
    this.record(rv);
    return rv;
  }

  /** Resolves INDIRECT-style text to a reference relative to a sheet. */
  resolveRefText(text: string, sheet: Sheet, a1: boolean, r: number, c: number): Value {
    const { sheet: sn, ref } = splitSheetRef(text);
    const sh = sn ? this.book.sheetByName(sn) : sheet;
    if (!sh) return ERR.ref;
    let rg: Range | null = null;
    if (a1) rg = parseRange(ref);
    else rg = parseR1C1(ref, r, c);
    if (!rg) {
      // A defined name or table
      if (/^[A-Za-z_\\][\w.]*$/.test(ref)) {
        const v = this.nameValue(ref, sn ?? undefined, this.makeCtx(sheet, r, c));
        return v;
      }
      return ERR.ref;
    }
    const rv: RefV = { k: 'ref', sheet: sh, ...rg };
    this.record(rv);
    return rv;
  }

  // ------------------------------------------------------------------------------------------
  // Ad-hoc evaluation (formula bar preview, conditional formatting, validation, goal seek, charts)

  /**
   * Evaluates formula text in the context of (sheet, r, c). When base is given, relative references
   * are interpreted relative to base and shifted to (r, c) (conditional formats, validation rules).
   */
  evaluate(formula: string, sheet: Sheet, r: number, c: number, base?: { r: number; c: number }): Value {
    const node = this.compile(formula.replace(/^=/, ''));
    if (node instanceof FormulaError) return ERR.name;
    const saveRec = this.recording;
    this.recording = null;
    try {
      const ctx = this.makeCtx(sheet, r, c, null, base ? { dr: r - base.r, dc: c - base.c } : null);
      return this.evalNode(node, ctx);
    } catch (e) {
      if (e instanceof Fail) return e.err;
      if (e instanceof CircularError) return ERR.circ;
      return ERR.value;
    } finally {
      this.recording = saveRec;
    }
  }

  evaluateScalar(formula: string, sheet: Sheet, r: number, c: number, base?: { r: number; c: number }): Scalar {
    const v = this.evaluate(formula, sheet, r, c, base);
    try { return toScalar(v, this.makeCtx(sheet, r, c)); } catch (e) { return e instanceof Fail ? e.err : ERR.value; }
  }

  evaluateMatrix(formula: string, sheet: Sheet, r = 0, c = 0): Matrix {
    const v = this.evaluate(formula, sheet, r, c);
    try { return toMatrix(v, this.makeCtx(sheet, r, c)); } catch (e) { return [[e instanceof Fail ? e.err : ERR.value]]; }
  }
}

class CircularError extends Error {}
/** Thrown when on-demand evaluation gets too deep; the cell is evaluated later from a fresh stack. */
class DeferError extends Error {}
const MAX_DEPTH = 400;

function wrap(f: () => Scalar): Scalar {
  try { return f(); } catch (e) { if (e instanceof Fail) return e.err; throw e; }
}

/** Results are rounded to 15 significant digits, as spreadsheets store them. */
function norm(v: Scalar): Scalar {
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) return ERR.num;
    if (v === 0) return 0;
    return +v.toPrecision(15);
  }
  return v;
}

function sameRange(a: Range | null, b: Range | null): boolean {
  if (!a || !b) return a === b;
  return a.r1 === b.r1 && a.c1 === b.c1 && a.r2 === b.r2 && a.c2 === b.c2;
}

function unionOf(a: Range | null, b: Range | null): Range | null {
  if (!a) return b; if (!b) return a;
  return { r1: Math.min(a.r1, b.r1), c1: Math.min(a.c1, b.c1), r2: Math.max(a.r2, b.r2), c2: Math.max(a.c2, b.c2) };
}

const arith = (f: (x: number, y: number) => number) => (a: Scalar, b: Scalar): Scalar => {
  if (a instanceof CellError) return a;
  if (b instanceof CellError) return b;
  return f(num(a), num(b));
};

const cmpOp = (f: (c: number) => boolean) => (a: Scalar, b: Scalar): Scalar => {
  if (a instanceof CellError) return a;
  if (b instanceof CellError) return b;
  return f(compareEq(a, b));
};

/** Comparison for = and relational operators: like compare() but with float tolerance. */
function compareEq(a: Scalar, b: Scalar): number {
  if (typeof a === 'number' && typeof b === 'number') {
    if (a === b) return 0;
    const d = Math.abs(a - b), m = Math.max(Math.abs(a), Math.abs(b));
    if (d <= m * 1e-15) return 0;
    return a < b ? -1 : 1;
  }
  return compare(a, b);
}

const BINOPS: Record<string, (a: Scalar, b: Scalar) => Scalar> = {
  '+': arith((x, y) => x + y),
  '-': arith((x, y) => x - y),
  '*': arith((x, y) => x * y),
  '/': arith((x, y) => (y === 0 ? fail(ERR.div0) : x / y)),
  '^': arith((x, y) => {
    if (x === 0 && y === 0) return fail(ERR.num);
    if (x === 0 && y < 0) return fail(ERR.div0);
    const r = Math.pow(x, y);
    return Number.isNaN(r) ? fail(ERR.num) : r;
  }),
  '&': (a, b) => (a instanceof CellError ? a : b instanceof CellError ? b : str(a) + str(b)),
  '=': cmpOp((c) => c === 0),
  '<>': cmpOp((c) => c !== 0),
  '<': cmpOp((c) => c < 0),
  '>': cmpOp((c) => c > 0),
  '<=': cmpOp((c) => c <= 0),
  '>=': cmpOp((c) => c >= 0),
};

/** R1C1 reference text (for INDIRECT(..., FALSE)). */
export function parseR1C1(t: string, r0: number, c0: number): Range | null {
  const part = (s: string): { r: number | null; c: number | null } | null => {
    const m = /^(?:R(\[-?\d+\]|\d+)?)?(?:C(\[-?\d+\]|\d+)?)?$/i.exec(s);
    if (!m || (!/^R/i.test(s) && !/C/i.test(s))) return null;
    const v = (x: string | undefined, base: number) => (x == null ? (x === undefined ? base : null) : x.startsWith('[') ? base + +x.slice(1, -1) : +x - 1);
    const hasR = /^R/i.test(s), hasC = /C/i.test(s);
    return { r: hasR ? v(m[1], r0) : null, c: hasC ? v(m[2], c0) : null };
  };
  const [a, b] = t.split(':');
  const pa = part(a);
  if (!pa) return null;
  const pb = b ? part(b) : pa;
  if (!pb) return null;
  const r1 = pa.r ?? 0, r2 = pb.r ?? (pa.r == null ? MAX_ROWS - 1 : r1);
  const c1 = pa.c ?? 0, c2 = pb.c ?? (pa.c == null ? MAX_COLS - 1 : c1);
  if ([r1, r2].some((x) => x < 0 || x >= MAX_ROWS) || [c1, c2].some((x) => x < 0 || x >= MAX_COLS)) return null;
  return { r1: Math.min(r1, r2), c1: Math.min(c1, c2), r2: Math.max(r1, r2), c2: Math.max(c1, c2) };
}

